package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
	"time"
)

const adaptiveConfigFile = "/etc/nethera-priority-adaptive.json"
const adaptiveService = "/etc/init.d/nethera-autorate"
const adaptiveOwner = "# Nethera priority adaptive controller"

type priorityAdaptiveConfig struct {
	Enabled          bool     `json:"enabled"`
	MinDownloadKbit  int      `json:"minDownloadKbit"`
	BaseDownloadKbit int      `json:"baseDownloadKbit"`
	Reflectors       []string `json:"reflectors"`
}
type priorityAdaptive struct {
	run                                      func(string, ...string) ([]byte, error)
	read                                     func(string) ([]byte, error)
	dir, configFile, serviceFile, healthFile string
}

func newPriorityAdaptive(run func(string, ...string) ([]byte, error)) *priorityAdaptive {
	return &priorityAdaptive{run: run, read: os.ReadFile, dir: "/var/run/nethera-priority", configFile: adaptiveConfigFile, serviceFile: adaptiveService, healthFile: "/var/run/cake-autorate/nethera-priority/nethera.last-response"}
}
func (a *priorityAdaptive) plan(c priorityControl, b priorityBandwidth) (*priorityAdaptiveConfig, error) {
	// Explicit cloud/manual settings override local commissioning adaptation.
	if c.Bandwidth != nil || !b.Enabled {
		return nil, nil
	}
	raw, err := a.read(a.configFile)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var p priorityAdaptiveConfig
	if err = json.Unmarshal(raw, &p); err != nil {
		return nil, err
	}
	if !p.Enabled {
		return nil, nil
	}
	if err = p.validate(b.DownloadKbit); err != nil {
		return nil, err
	}
	return &p, nil
}
func (p priorityAdaptiveConfig) validate(maximum int) error {
	if p.MinDownloadKbit < 128 || p.MinDownloadKbit > p.BaseDownloadKbit || p.BaseDownloadKbit > maximum || maximum > 1000000 || len(p.Reflectors) < 2 || len(p.Reflectors) > 6 {
		return errors.New("invalid adaptive min/base/maximum or reflectors")
	}
	for _, s := range p.Reflectors {
		ip := net.ParseIP(s)
		if ip == nil || ip.To4() == nil || !ip.IsGlobalUnicast() || ip.IsPrivate() || ip.IsLoopback() {
			return errors.New("adaptive reflectors must be public IPv4 addresses")
		}
	}
	return nil
}
func (a *priorityAdaptive) owned() bool {
	b, e := a.read(a.serviceFile)
	return e == nil && bytes.Contains(b, []byte(adaptiveOwner))
}
func (a *priorityAdaptive) pid() int {
	raw, e := a.run("ubus", "call", "service", "list", `{"name":"nethera-autorate"}`)
	if e != nil {
		return 0
	}
	var services map[string]struct {
		Instances map[string]struct {
			Running bool `json:"running"`
			PID     int  `json:"pid"`
		} `json:"instances"`
	}
	if json.Unmarshal(raw, &services) != nil {
		return 0
	}
	for _, i := range services["nethera-autorate"].Instances {
		if i.Running && i.PID > 0 {
			return i.PID
		}
	}
	return 0
}
func (a *priorityAdaptive) running() bool { return a.pid() > 0 }
func (a *priorityAdaptive) stop() error {
	if !a.owned() {
		return nil
	}
	pid := a.pid()
	if pid <= 0 {
		return nil
	}
	if _, e := a.run(a.serviceFile, "stop"); e != nil {
		return e
	}
	for i := 0; i < 50; i++ {
		if syscall.Kill(pid, 0) != nil && !a.running() {
			return nil
		}
		time.Sleep(100 * time.Millisecond)
	}
	return errors.New("adaptive controller did not stop; queues left unchanged")
}
func renderAdaptive(p priorityAdaptiveConfig, b priorityBandwidth, wan, lan string) ([]byte, error) {
	if !interfacePattern.MatchString(wan) || !interfacePattern.MatchString(lan) {
		return nil, errors.New("invalid adaptive interface")
	}
	if err := p.validate(b.DownloadKbit); err != nil {
		return nil, err
	}
	var out strings.Builder
	fmt.Fprintf(&out, "# Generated by Nethera; no user-supplied shell code.\ndl_if='%s'\nul_if='%s'\nadjust_dl_shaper_rate=1\nadjust_ul_shaper_rate=0\nmin_dl_shaper_rate_kbps=%d\nbase_dl_shaper_rate_kbps=%d\nmax_dl_shaper_rate_kbps=%d\nmin_ul_shaper_rate_kbps=%d\nbase_ul_shaper_rate_kbps=%d\nmax_ul_shaper_rate_kbps=%d\n", lan, wan, p.MinDownloadKbit, p.BaseDownloadKbit, b.DownloadKbit, b.UploadKbit, b.UploadKbit, b.UploadKbit)
	out.WriteString("reflectors=(")
	for _, s := range p.Reflectors {
		fmt.Fprintf(&out, "'%s' ", s)
	}
	out.WriteString(")\nrandomize_reflectors=0\n")
	fmt.Fprintf(&out, "no_pingers=%d\nreflector_ping_interval_s=0.3\nping_extra_args='-I %s'\n", min(3, len(p.Reflectors)), wan)
	out.WriteString("enable_sleep_function=0\nconnection_active_thr_kbps=1000\ndebug=0\nlog_to_file=1\nlog_file_max_size_KB=128\nlog_file_max_time_mins=5\nlog_file_path_override='/var/run/nethera-priority'\noutput_cake_changes=1\noutput_summary_stats=0\noutput_load_stats=0\noutput_processing_stats=0\noutput_reflector_stats=0\n")
	return []byte(out.String()), nil
}

// prepare returns whether a matching controller already owns the rate.
func (a *priorityAdaptive) prepare(p priorityAdaptiveConfig, b priorityBandwidth, wan, lan string) (bool, error) {
	if !a.owned() {
		return false, errors.New("adaptive service missing or foreign; left unchanged")
	}
	desired, e := renderAdaptive(p, b, wan, lan)
	if e != nil {
		return false, e
	}
	path := filepath.Join(a.dir, "config.nethera-priority.sh")
	old, _ := a.read(path)
	if bytes.Equal(old, desired) && a.running() {
		return true, nil
	}
	if e = a.stop(); e != nil {
		return false, e
	}
	if e = os.MkdirAll(a.dir, 0700); e != nil {
		return false, e
	}
	if _, e = writeIfChanged(path, string(desired)); e != nil {
		return false, e
	}
	return false, nil
}
func (a *priorityAdaptive) healthy(now time.Time) bool {
	if !a.owned() {
		return false
	}
	pid := a.pid()
	if pid <= 0 {
		return false
	}
	b, e := a.read(a.healthFile)
	if e != nil {
		return false
	}
	f := strings.Fields(string(b))
	if len(f) != 2 {
		return false
	}
	sec, e := strconv.ParseInt(f[0], 10, 64)
	p, pe := strconv.Atoi(f[1])
	return e == nil && pe == nil && p == pid && now.Unix()-sec >= 0 && now.Unix()-sec <= 10
}
func (a *priorityAdaptive) start() error {
	if !a.running() {
		if _, e := a.run(a.serviceFile, "start"); e != nil {
			return e
		}
	}
	for i := 0; i < 15; i++ {
		if a.healthy(time.Now()) {
			return nil
		}
		time.Sleep(200 * time.Millisecond)
	}
	return errors.New("adaptive controller waiting for fresh reflector replies")
}
