package main

// DNS control (issues #23 AdBlocker and #25 block websites).
//
// The backend publishes the complete desired state as one retained message on
// nethera/<id>/config/dns. The agent checks it, writes the dnsmasq and firewall files,
// switches adblock-fast on or off and reports the result on nethera/<id>/telemetry/control.
// The last valid state is saved on flash, so the blocks come back after a power cut
// even when the router has no internet yet.

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	maxDomains = 2000
	maxDevices = 100

	dnsmasqFileName = "nethera-block.conf"
	nftFileName     = "90-nethera.nft"
)

// dnsControl is the desired state sent by the backend
type dnsControl struct {
	V       int      `json:"v"`
	Version int64    `json:"version"`
	Adblock bool     `json:"adblock"`
	Network []string `json:"network"`
	// Devices maps a MAC address to the domains blocked only for that device
	Devices map[string][]string `json:"devices"`
}

// controlPayload is the agent's answer: which version is applied and what the router really runs
type controlPayload struct {
	V       int          `json:"v"`
	TS      int64        `json:"ts"`
	Version int64        `json:"version"`
	Applied bool         `json:"applied"`
	Adblock adblockState `json:"adblock"`
	Error   string       `json:"error,omitempty"`
}

type adblockState struct {
	Installed bool `json:"installed"`
	Enabled   bool `json:"enabled"`
}

var (
	domainPattern = regexp.MustCompile(`^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$`)
	macPattern    = regexp.MustCompile(`^([0-9a-f]{2}:){5}[0-9a-f]{2}$`)
)

// parseDNSControl reads and checks a message. The agent runs as root and writes the
// values into config files, so anything that is not a plain domain or MAC is refused.
func parseDNSControl(data []byte) (dnsControl, error) {
	var c dnsControl
	if err := json.Unmarshal(data, &c); err != nil {
		return dnsControl{}, fmt.Errorf("invalid JSON: %w", err)
	}
	if c.V != schemaVersion {
		return dnsControl{}, fmt.Errorf("unsupported schema version %d", c.V)
	}
	if c.Version <= 0 {
		return dnsControl{}, errors.New("version must be a positive number")
	}

	network, err := cleanDomains(c.Network)
	if err != nil {
		return dnsControl{}, err
	}
	c.Network = network

	if len(c.Devices) > maxDevices {
		return dnsControl{}, fmt.Errorf("more than %d devices", maxDevices)
	}
	devices := map[string][]string{}
	total := len(network)
	for mac, domains := range c.Devices {
		mac = strings.ToLower(strings.TrimSpace(mac))
		if !macPattern.MatchString(mac) {
			return dnsControl{}, fmt.Errorf("invalid MAC address %q", mac)
		}
		cleaned, err := cleanDomains(domains)
		if err != nil {
			return dnsControl{}, err
		}
		total += len(cleaned)
		if len(cleaned) > 0 {
			devices[mac] = cleaned
		}
	}
	if total > maxDomains {
		return dnsControl{}, fmt.Errorf("more than %d domains", maxDomains)
	}
	c.Devices = devices
	return c, nil
}

// cleanDomains lowercases, checks, sorts and de-duplicates a domain list
func cleanDomains(domains []string) ([]string, error) {
	seen := map[string]bool{}
	result := []string{}
	for _, d := range domains {
		d = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(d)), ".")
		if len(d) > 253 || !domainPattern.MatchString(d) {
			return nil, fmt.Errorf("invalid domain %q", d)
		}
		if !seen[d] {
			seen[d] = true
			result = append(result, d)
		}
	}
	sort.Strings(result)
	return result, nil
}

// setName is the firewall set that holds the blocked addresses of one device
func setName(mac string, family int) string {
	return fmt.Sprintf("nethera_%s_%d", strings.ReplaceAll(mac, ":", ""), family)
}

// sortedMACs keeps the generated files stable, so an unchanged state changes no file
func sortedMACs(devices map[string][]string) []string {
	macs := make([]string, 0, len(devices))
	for mac := range devices {
		macs = append(macs, mac)
	}
	sort.Strings(macs)
	return macs
}

// dnsmasqConfig blocks network domains for everyone (address=/x/ answers NXDOMAIN) and
// lets dnsmasq put the addresses of device domains into that device's firewall sets.
func dnsmasqConfig(c dnsControl) string {
	var b strings.Builder
	b.WriteString("# Generated by nethera-agent, do not edit\n")
	for _, d := range c.Network {
		fmt.Fprintf(&b, "address=/%s/\n", d)
	}
	for _, mac := range sortedMACs(c.Devices) {
		for _, d := range c.Devices[mac] {
			fmt.Fprintf(&b, "nftset=/%s/4#inet#fw4#%s,6#inet#fw4#%s\n", d, setName(mac, 4), setName(mac, 6))
		}
	}
	return b.String()
}

// nftConfig is included by fw4 inside "table inet fw4". Traffic from a blocked device to
// an address in its set is rejected. The file is empty when no device has own blocks.
func nftConfig(c dnsControl) string {
	if len(c.Devices) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("# Generated by nethera-agent, do not edit\n")
	macs := sortedMACs(c.Devices)
	for _, mac := range macs {
		fmt.Fprintf(&b, "set %s { type ipv4_addr; flags timeout; timeout 1h; }\n", setName(mac, 4))
		fmt.Fprintf(&b, "set %s { type ipv6_addr; flags timeout; timeout 1h; }\n", setName(mac, 6))
	}
	b.WriteString("chain nethera_block {\n\ttype filter hook forward priority filter - 5; policy accept;\n")
	for _, mac := range macs {
		fmt.Fprintf(&b, "\tether saddr %s ip daddr @%s reject\n", mac, setName(mac, 4))
		fmt.Fprintf(&b, "\tether saddr %s ip6 daddr @%s reject\n", mac, setName(mac, 6))
	}
	b.WriteString("}\n")
	return b.String()
}

// writeIfChanged writes content to path and reports whether the file changed. An empty
// content removes the file.
func writeIfChanged(path, content string) (bool, error) {
	old, err := os.ReadFile(path)
	exists := err == nil
	if content == "" {
		if !exists {
			return false, nil
		}
		return true, os.Remove(path)
	}
	if exists && bytes.Equal(old, []byte(content)) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	// Write to a temporary file first, so a power cut never leaves half a file behind
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, path)
}

// dnsmasqDir finds dnsmasq's include directory, for example /tmp/dnsmasq.cfg01411c.d
func dnsmasqDir(pattern string) (string, error) {
	dirs, _ := filepath.Glob(pattern)
	if len(dirs) == 0 {
		return "", fmt.Errorf("no dnsmasq include directory matches %s", pattern)
	}
	return dirs[0], nil
}

// dnsmasqHasNftset reports whether this dnsmasq build can fill firewall sets (dnsmasq-full)
func dnsmasqHasNftset(src Sources) bool {
	out, err := src.Run("dnsmasq", "--version")
	return err == nil && strings.Contains(string(out), " nftset") && !strings.Contains(string(out), "no-nftset")
}

// applyDNSControl brings the router to the desired state and returns what it really runs.
// It only restarts a service when one of its files changed.
func applyDNSControl(src Sources, c dnsControl) controlPayload {
	result := controlPayload{V: schemaVersion, TS: src.Now().Unix(), Version: c.Version}
	var problems []string

	// Per-device blocks need dnsmasq-full; without it only the network blocks are applied
	if len(c.Devices) > 0 && !dnsmasqHasNftset(src) {
		problems = append(problems, "per-device blocking needs dnsmasq-full")
		c.Devices = nil
	}

	nftChanged, err := writeIfChanged(filepath.Join(src.NftDir, nftFileName), nftConfig(c))
	if err != nil {
		problems = append(problems, "firewall file: "+err.Error())
	}
	// The sets have to exist before dnsmasq starts filling them
	if nftChanged {
		if _, err := src.Run("fw4", "reload"); err != nil {
			problems = append(problems, "fw4 reload: "+err.Error())
		}
	}

	dir, err := dnsmasqDir(src.DnsmasqDirGlob)
	if err != nil {
		problems = append(problems, err.Error())
	} else {
		changed, err := writeIfChanged(filepath.Join(dir, dnsmasqFileName), dnsmasqConfig(c))
		if err != nil {
			problems = append(problems, "dnsmasq file: "+err.Error())
		}
		if changed || nftChanged {
			if _, err := src.Run("/etc/init.d/dnsmasq", "restart"); err != nil {
				problems = append(problems, "dnsmasq restart: "+err.Error())
			}
		}
	}

	if err := applyAdblock(src, c.Adblock); err != nil {
		problems = append(problems, "adblock: "+err.Error())
	}
	result.Adblock = readAdblock(src)

	result.Applied = len(problems) == 0
	result.Error = strings.Join(problems, "; ")
	return result
}

// applyAdblock installs adblock-fast once when it is wanted and switches it on or off
func applyAdblock(src Sources, enabled bool) error {
	state := readAdblock(src)
	if state.Enabled == enabled {
		return nil
	}
	if enabled && !state.Installed {
		// Installing needs internet and can take a minute
		if _, err := src.RunLong("apk", "update"); err != nil {
			return fmt.Errorf("apk update: %w", err)
		}
		if _, err := src.RunLong("apk", "add", "adblock-fast"); err != nil {
			return fmt.Errorf("apk add adblock-fast: %w", err)
		}
	}
	if !enabled && !state.Installed {
		return nil
	}

	value, action, boot := "0", "stop", "disable"
	if enabled {
		value, action, boot = "1", "start", "enable"
	}
	steps := [][]string{
		{"uci", "set", "adblock-fast.config.enabled=" + value},
		{"uci", "commit", "adblock-fast"},
		{src.AdblockInit, boot},
		{src.AdblockInit, action},
	}
	for _, step := range steps {
		if _, err := src.RunLong(step[0], step[1:]...); err != nil {
			return fmt.Errorf("%s: %w", strings.Join(step, " "), err)
		}
	}
	return nil
}

// readAdblock checks what is really installed and configured, not what was requested
func readAdblock(src Sources) adblockState {
	if _, err := os.Stat(src.AdblockInit); err != nil {
		return adblockState{}
	}
	out, err := src.Run("uci", "-q", "get", "adblock-fast.config.enabled")
	return adblockState{Installed: true, Enabled: err == nil && strings.TrimSpace(string(out)) == "1"}
}

// loadSavedControl reads the state saved on flash by the last successful message
func loadSavedControl(path string) (dnsControl, bool) {
	data, err := os.ReadFile(path)
	if err != nil {
		return dnsControl{}, false
	}
	c, err := parseDNSControl(data)
	return c, err == nil
}

// saveControl keeps the message on flash; unchanged states are not rewritten, to spare the flash
func saveControl(path string, data []byte) error {
	_, err := writeIfChanged(path, string(data)+"\n")
	return err
}
